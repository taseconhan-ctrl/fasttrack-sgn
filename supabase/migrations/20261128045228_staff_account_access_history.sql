create table if not exists public.staff_account_access_history (
  id bigint generated by default as identity primary key,
  account_id uuid not null references public.staff_pin_accounts(id) on delete restrict,
  staff_member_id uuid references public.staff_members(id) on delete set null,
  staff_name text not null,
  username text not null,
  user_agent text,
  logged_in_at timestamptz not null default now()
);
create index if not exists staff_account_access_history_logged_in_at_idx
  on public.staff_account_access_history (logged_in_at desc);
create index if not exists staff_account_access_history_staff_logged_idx
  on public.staff_account_access_history (staff_member_id, logged_in_at desc);
alter table public.staff_account_access_history enable row level security;
revoke all on public.staff_account_access_history from anon, authenticated;
