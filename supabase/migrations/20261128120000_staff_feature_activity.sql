-- Theo dõi chức năng nhân viên đã sử dụng.
-- Idempotent: nếu bảng staff_feature_activity đã được tạo trên Supabase thì chỉ bổ sung cột/chỉ mục còn thiếu.
-- Dữ liệu chỉ do Edge Function (service role) ghi và đọc; trình duyệt không truy cập trực tiếp bảng.

create table if not exists public.staff_feature_activity (
  id bigint generated by default as identity primary key,
  account_id uuid not null references public.staff_pin_accounts(id) on delete restrict,
  staff_member_id uuid references public.staff_members(id) on delete set null,
  feature text not null,
  event_id uuid not null,
  occurred_at timestamptz not null default now()
);

alter table public.staff_feature_activity add column if not exists account_id uuid;
alter table public.staff_feature_activity add column if not exists staff_member_id uuid;
alter table public.staff_feature_activity add column if not exists feature text;
alter table public.staff_feature_activity add column if not exists event_id uuid;
alter table public.staff_feature_activity add column if not exists occurred_at timestamptz not null default now();

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'staff_feature_activity_feature_check') then
    alter table public.staff_feature_activity
      add constraint staff_feature_activity_feature_check
      check (feature in ('soan_booking','doi_soat','don_khach','ung_don_khach','xep_lich','quan_ly_tai_khoan'));
  end if;
end $$;

-- Chống ghi nhận trùng: một mã sự kiện chỉ được lưu một lần (gửi lại khi mất mạng không tạo thêm lượt).
create unique index if not exists staff_feature_activity_event_id_key
  on public.staff_feature_activity (event_id);
create index if not exists staff_feature_activity_staff_feature_time_idx
  on public.staff_feature_activity (staff_member_id, feature, occurred_at desc);
create index if not exists staff_feature_activity_time_idx
  on public.staff_feature_activity (occurred_at desc);

alter table public.staff_feature_activity enable row level security;
revoke all on public.staff_feature_activity from anon, authenticated;

-- Thống kê số lượt theo nhân viên và chức năng, kèm lần dùng gần nhất.
create or replace function public.staff_feature_activity_summary()
returns table (staff_member_id uuid, feature text, uses bigint, last_used_at timestamptz)
language sql
stable
as $$
  select a.staff_member_id, a.feature, count(*)::bigint, max(a.occurred_at)
  from public.staff_feature_activity a
  where a.staff_member_id is not null
  group by a.staff_member_id, a.feature
$$;
revoke all on function public.staff_feature_activity_summary() from public, anon, authenticated;
